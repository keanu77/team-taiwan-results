import assert from "node:assert/strict";
import { isTodayQuery, periodQuery, readResultQuery, resultQueryHref, todayQuery, toggleStatusQuery } from "../src/components/results/resultQuery";
const today = "2026-09-23";
const read = (params: string) => readResultQuery(new URLSearchParams(params), today);
assert.deepEqual(read(""), { period: true, date: today, sport: "", status: "" }, "first visit defaults to the entire competition period");
assert.equal(read("sport=SWM").period, true, "sport-only links keep the default period scope");
assert.equal(read("date=2026-09-20").period, false, "existing date-specific links remain single-day queries");
assert.equal(read("range=day").period, false, "an explicit day scope can still select today");
assert.deepEqual(read("range=period&date=2026-10-04"), { period: true, date: today, sport: "", status: "" }, "period always ends today regardless of previously selected day");
assert.equal(read("date=2026-09-10").date, "2026-09-10");
assert.equal(read("date=2026-09-31").date, today);
assert.equal(read("date=2027-01-01").date, "2026-10-04");
const query = { period: true, date: today, sport: "BASKETBALL-women", status: "OFFICIAL" };
assert.deepEqual(read(resultQueryHref(query).split("?")[1]), query, "shareable URLs retain applied sport and status filters");
assert.equal(resultQueryHref({ period: true, date: today, sport: "", status: "" }), "/?range=period");
assert.equal(resultQueryHref({ period: false, date: "2026-09-10", sport: "", status: "" }), "/?date=2026-09-10");
assert.equal(read("sport=%3Cscript%3E&status=__invalid__").sport, "");
assert.equal(readResultQuery(new URLSearchParams(), "").date, "", "initial client render must wait for local Japan date");
assert.equal(readResultQuery(new URLSearchParams(), "").period, true, "the default scope is stable before the Japan date initializes");
const filtered = { period: true, date: today, sport: "BDM", status: "" };
assert.deepEqual(toggleStatusQuery(filtered, "RUNNING"), { ...filtered, status: "RUNNING" }, "status chips keep the sport filter");
assert.deepEqual(toggleStatusQuery({ ...filtered, status: "RUNNING" }, "RUNNING"), filtered, "pressing the active chip clears it");
assert.equal(filtered.status, "", "toggling returns a new query");
assert.deepEqual(todayQuery(today), { period: false, date: today, sport: "", status: "" });
assert.deepEqual(todayQuery("2026-12-01").date, "2026-10-04", "today shortcut clamps to the competition dates");
assert.deepEqual(periodQuery(today), { period: true, date: today, sport: "", status: "" });
assert.equal(isTodayQuery(todayQuery(today), today), true);
assert.equal(isTodayQuery(periodQuery(today), today), false);
assert.equal(isTodayQuery({ period: false, date: "2026-09-20", sport: "", status: "" }, today), false);
console.info("PASS result query shortcuts: status chip toggle, today and period shortcuts");
console.info("PASS result query: today-bounded period, explicit day, invalid-date fallback, shareable applied filters and client initialization");
